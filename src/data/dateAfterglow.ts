export function getDateAfterglow(characterId: string, placeId: string, finalHeart: number): DateAfterglow {
  const lines = afterglowLines[characterId] ?? afterglowLines.char_001
  const tone = finalHeart >= 4 ? 'warm' : finalHeart >= 2 ? 'playful' : 'quiet'
  return {
    title: finalHeart >= 4 ? '다음 약속을 기다리는 메시지' : '데이트 뒤에 도착한 메시지',
    line: lines[tone],
    tone,
    placeName: placeNames[placeId] ?? '오늘의 장소',
  }
}
