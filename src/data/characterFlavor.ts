export function getMyRoomEndingDialogue(characterId: string, day: number) {
  const lines = workroomDialogue[characterId]?.complete ?? ['오늘도 같이 있어도 될까요?']
  return lines[Math.max(0, day - 1) % lines.length] ?? lines[0]
}

export function getMyRoomRivalryLine(characterId: string, otherName: string, day: number) {
  const lines = myRoomRivalryLines[characterId] ?? ['{other} 씨도 오셨네요. 오늘은 조금 북적이겠어요.']
  const line = lines[Math.max(0, day - 1) % lines.length] ?? lines[0]
  return line.replaceAll('{other}', otherName)
}

export function getWorkroomDialogue(characterId: string, affection: number, completed: boolean, day: number) {
  const tier: WorkroomDialogueTier = completed ? 'complete' : affection >= 80 ? 'high' : affection >= 40 ? 'mid' : 'low'
  const lines = workroomDialogue[characterId]?.[tier] ?? ['오늘도 좋은 하루 보내세요.']
  return lines[Math.max(0, day - 1) % lines.length] ?? lines[0]
}

