export function getCharacterThemeLine(characterId: string) { return themeLines[characterId] ?? '조금씩, 이 사람을 알아가는 중.' }
export function getReunionLine(characterId: string, encounterCount: number) {
  const lines = reunionLines[characterId] ?? ['또 만났네요.']
  return lines[Math.max(0, encounterCount - 2) % lines.length] ?? lines[0]
}
export function getPostRouteLine(characterId: string, day: number) {
  const lines = postRouteLines[characterId] ?? ['완성된 인연이 작업실의 하루에 조용히 스며들었다.']
  return lines[(Math.max(1, day) - 1) % lines.length] ?? lines[0]
}

